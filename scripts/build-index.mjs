// Regenerate data/index.json from every brand file in data/, and stamp sw.js with a content-hash cache name.
// Never edit data/index.json by hand. Usage: node scripts/build-index.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { validate, NON_BRAND, MATERIALS } from './validate.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'data');
const MATERIAL_GROUPS = Object.entries(JSON.parse(fs.readFileSync(path.join(dataDir, 'materials.json'))).groups);
const COOLANTS = ['flood', 'air', 'dry'];
const SHELL = ['./', 'index.html', 'app.js', 'calc.js', 'manifest.json', 'data/index.json', 'data/threads.json'];

const files = fs.readdirSync(dataDir).filter(f => f.endsWith('.json') && !NON_BRAND.has(f) && !f.startsWith('_')).sort();
const hash = crypto.createHash('sha256');
const out = []; const errors = [];
for (const f of files) {
  const raw = fs.readFileSync(path.join(dataDir, f), 'utf8'); hash.update(f).update(raw);
  let doc; try { doc = JSON.parse(raw); } catch (e) { errors.push(`${f}: not valid JSON`); continue; }
  const e = validate(doc, f); if (e.length) { errors.push(...e); continue; }
  const tools = doc.tools.map((t, i) => ({ i, mode: t.mode, brand: t.brand, series: t.series,
    ...(t.type ? { type: t.type } : {}),
    isos: [...new Set(t.conditions.map(c => c.iso))].sort(),
    dataIsos: [...new Set(t.conditions.filter(c => c.sfm || c.feed).map(c => c.iso))].sort(),
    mats: [...new Set(t.conditions.flatMap(c => c.materials ?? []))].sort(),
    shop: t.conditions.some(c => c.status === 'shop-proven') }));
  out.push({ file: f, brand: doc.brand, modes: [...new Set(tools.map(t => t.mode))].sort(), records: doc.tools.reduce((n, t) => n + t.conditions.length, 0), tools });
}
if (errors.length) { errors.forEach(x => console.error(x)); console.error(`build-index: ${errors.length} error(s); index not written`); process.exit(1); }
for (const f of ['app.js', 'calc.js', 'index.html', 'manifest.json', 'data/threads.json', 'data/materials.json']) hash.update(fs.readFileSync(path.join(root, f)));
const version = 'fs-' + hash.digest('hex').slice(0, 10);
const index = { schema: 1, note: 'GENERATED by scripts/build-index.mjs. Do not edit.', version, materialGroups: MATERIAL_GROUPS, materials: MATERIALS, coolants: COOLANTS, files: out };
fs.writeFileSync(path.join(dataDir, 'index.json'), JSON.stringify(index));
const sw = path.join(root, 'sw.js');
fs.writeFileSync(sw, fs.readFileSync(sw, 'utf8').replace(/^const C='[^']*',F=\[[^\]]*\];/m, `const C='${version}',F=${JSON.stringify(SHELL).replace(/"/g, "'")};`));
console.log(`index: ${out.length} files, ${out.reduce((n, f) => n + f.tools.length, 0)} tools, ${out.reduce((n, f) => n + f.records, 0)} records; sw ${version}`);
